CREATE OR REPLACE FUNCTION dp_touch_updated_time() RETURNS trigger AS $$
BEGIN
    NEW.updated_time = now() AT TIME ZONE 'UTC';
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE repository_v1 (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner varchar(39) NOT NULL,
    repo varchar(100) NOT NULL,
    license varchar(64) NOT NULL,
    stars integer NULL,
    forks integer NULL,
    open_issues integer NULL,
    created_time timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_time timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE UNIQUE INDEX uq_repository_v1_owner_repo
    ON repository_v1 (lower(owner), lower(repo));

CREATE TRIGGER touch_updated_time BEFORE UPDATE ON repository_v1
    FOR EACH ROW EXECUTE FUNCTION dp_touch_updated_time();

CREATE TABLE plugin_v1 (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(214) NOT NULL,
    npm_name varchar(214) NOT NULL,
    repository_id integer NULL,
    github_path varchar(128) NOT NULL,
    created_time timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_time timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE INDEX idx_plugin_v1_name ON plugin_v1 (name);
CREATE INDEX idx_plugin_v1_npm_name ON plugin_v1 (npm_name);
CREATE INDEX idx_plugin_v1_repository_id ON plugin_v1 (repository_id);

CREATE TRIGGER touch_updated_time BEFORE UPDATE ON plugin_v1
    FOR EACH ROW EXECUTE FUNCTION dp_touch_updated_time();

CREATE TABLE plugin_version_v1 (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plugin_id integer NOT NULL,
    seq integer NOT NULL,
    package_version varchar(64) NOT NULL,
    dsh_version varchar(64) NOT NULL,
    created_time timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_time timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE UNIQUE INDEX uq_plugin_version_v1_plugin_id_seq
    ON plugin_version_v1 (plugin_id, seq);

CREATE TRIGGER touch_updated_time BEFORE UPDATE ON plugin_version_v1
    FOR EACH ROW EXECUTE FUNCTION dp_touch_updated_time();

CREATE TABLE evaluation_v1 (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plugin_id integer NOT NULL,
    version integer NOT NULL,
    sha char(40) NOT NULL,
    evaluated_at timestamp NOT NULL,
    evaluator varchar(64) NOT NULL,
    result jsonb NOT NULL,
    created_time timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_time timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE UNIQUE INDEX uq_evaluation_v1_plugin_id_evaluated_at
    ON evaluation_v1 (plugin_id, evaluated_at);

CREATE TRIGGER touch_updated_time BEFORE UPDATE ON evaluation_v1
    FOR EACH ROW EXECUTE FUNCTION dp_touch_updated_time();
